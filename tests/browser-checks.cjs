/* Run against a disposable Development demo. Requires Playwright and Chromium. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const baseUrl = process.env.DASHBOARD_URL || 'http://localhost:5080';
const output = process.env.SCREENSHOT_DIR || '/tmp/instrumenthub-browser';
let passed = 0;
function check(value, label) { assert.ok(value, label); passed++; console.log('PASS: ' + label); }
(async () => {
 fs.mkdirSync(output, { recursive: true });
 const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
 try {
 const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
 const errors = []; page.on('pageerror', e => errors.push(e.message));
 page.on('console', m => { if(m.type() === 'error') errors.push(m.text()); });
 page.on('requestfailed', request => errors.push(request.url() + ': ' + request.failure()?.errorText));
 await page.goto(baseUrl);
 await page.getByRole('heading', { name: 'Recent calibration tasks' }).waitFor({ timeout: 60000 });
 check(await page.locator('tbody tr').count() === 7, 'dashboard paginates seven instruments');
 check(await page.getByRole('button', { name: 'Overdue calibrations' }).count() === 1, 'overdue stat is actionable');
 await page.screenshot({ path: output + '/desktop.png', fullPage: true });
 await page.getByRole('button', { name: 'Overdue calibrations' }).click();
 check((await page.locator('tbody .badge').allTextContents()).every(s => s.includes('Overdue')), 'overdue stat filters table');
 await page.getByRole('button', { name: 'All equipment', exact: false }).click();
 const search = page.getByRole('textbox', { name: 'Search equipment', exact: true });
 await search.fill('Gas chromatograph');
 await page.getByRole('button', { name: /Gas chromatograph/ }).waitFor();
 check(await page.locator('tbody tr').count() === 1, 'table search filters instruments');
 await search.fill('');
 await page.getByRole('button', { name: 'Filters', exact: true }).click();
 await page.getByLabel('Calibration health', { exact: true }).selectOption('Due Soon');
 check((await page.locator('tbody .badge').allTextContents()).every(s=>s.includes('Due Soon')), 'due-soon filter');
 await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
 await page.getByRole('button', { name: 'Filters', exact: true }).click();
 const suffix = Date.now().toString();
 await page.getByRole('button', { name: 'Add instrument', exact: true }).click();
 let dialog = page.getByRole('dialog');
 await dialog.getByLabel('Asset ID').fill('UI-' + suffix);
 await dialog.getByLabel('Instrument name').fill('Browser test gauge');
 await dialog.getByLabel('Department').fill('Browser validation');
 await dialog.getByLabel('Model / manufacturer').fill('UI · Model 1');
 const due = new Date(); due.setUTCDate(due.getUTCDate()+60);
 await dialog.getByLabel('Next due date').fill(due.toISOString().slice(0,10));
 await dialog.getByRole('button', { name: 'Save instrument' }).click();
 await page.getByRole('status').filter({hasText:'Instrument added'}).waitFor();
 await page.getByRole('textbox', { name: 'Search equipment', exact: true }).fill('UI-' + suffix);
 await page.getByRole('button', { name: 'Browser test gauge' }).click();
 dialog = page.getByRole('dialog');
 await dialog.getByLabel('Manual status').selectOption('Out of Service');
 await dialog.getByRole('button', { name: 'Save instrument' }).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 await page.getByRole('status').filter({hasText:'Instrument details updated'}).waitFor();
 check(await page.locator('tbody .badge').textContent() === 'Out of Service', 'edit preserves manual override');
 await page.getByRole('button', { name: 'Browser test gauge' }).click();
 await page.getByRole('dialog').getByLabel('Manual status').selectOption('Active');
 await page.getByRole('dialog').getByRole('button', { name: 'Save instrument' }).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 await page.getByRole('status').filter({hasText:'Instrument details updated'}).waitFor();
 check(await page.locator('tbody .badge').textContent() === 'Calibrated', 'editing recalculates health');
 const pdf = Buffer.from('%PDF-1.4\n1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n2 0 obj\n<< /Type /Pages /Kids [] /Count 0 >>\nendobj\ntrailer\n<< /Root 1 0 R >>\n%%EOF\n');
 await page.getByLabel('Upload certificate for UI-' + suffix).setInputFiles({ name:'browser-check.pdf', mimeType:'application/pdf', buffer: pdf });
 await page.getByRole('status').filter({hasText:'Certificate uploaded'}).waitFor();
 await page.getByRole('link', { name:'Certificates', exact:true }).click();
 const documentRow = page.locator('tbody tr').filter({hasText:'UI-' + suffix});
 await documentRow.waitFor();
 const downloaded = page.waitForEvent('download');
 await documentRow.getByRole('button',{name:'Download'}).click();
 const download = await downloaded; const path = await download.path();
 check(fs.readFileSync(path).equals(pdf), 'browser certificate upload/download preserves bytes');
 await page.getByRole('link',{name:'Repair Logs',exact:true}).click();
 await page.getByRole('button',{name:'Log repair',exact:true}).click();
 dialog=page.getByRole('dialog');
 const optionValue = await dialog.getByRole('option').filter({hasText:'UI-' + suffix}).getAttribute('value');
 await dialog.getByLabel('Instrument', {exact:false}).selectOption(optionValue);
 await dialog.getByLabel('Issue description').fill('Browser validation issue');
 await dialog.getByLabel('Assigned technician').fill('UI technician');
 await dialog.getByRole('button',{name:'Create work order'}).click();
 await page.getByRole('status').filter({hasText:'Repair logged'}).waitFor();
 const repairRow=page.locator('tbody tr').filter({hasText:'Browser validation issue'});
 check((await repairRow.textContent()).includes('In Progress'),'browser logs repair');
 await repairRow.getByRole('button',{name:'Complete'}).click();
 await page.getByRole('status').filter({hasText:'Repair completed'}).waitFor();
 check((await repairRow.textContent()).includes('Completed'),'browser completes repair');
 await page.getByRole('link',{name:'Inventory',exact:true}).click();
 const downloadExport=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export',exact:true}).click();
 check((await downloadExport).suggestedFilename().endsWith('.csv'),'browser exports CSV');
 const csv='AssetId,Name,Department\nUI-CSV-'+suffix+',Browser imported meter,Browser validation\n';
 await page.locator('.file-label input').setInputFiles({name:'browser-import.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
 await page.getByRole('status').filter({hasText:'Imported 1 instruments'}).waitFor();
 check(true,'browser imports CSV with only required columns');
 await page.getByRole('link',{name:'Dashboard',exact:true}).click();
 await page.getByRole('heading',{name:'Equipment overview',exact:true}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(300);
 check(await page.locator('body').evaluate(e=>e.scrollWidth) === 390,'mobile page has no horizontal overflow');
 check(await page.locator('.sidebar').evaluate(e=>e.getBoundingClientRect().right) <= 0,'mobile sidebar starts offscreen');
 await page.screenshot({path:output+'/mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Open navigation',exact:true}).click();
 await page.waitForTimeout(300);
 check(await page.getByRole('link',{name:'Inventory',exact:true}).isVisible(),'mobile navigation opens');
 await page.getByRole('link',{name:'Inventory',exact:true}).click();
 await page.waitForTimeout(300);
 check(await page.locator('.sidebar').evaluate(e=>e.getBoundingClientRect().right) <= 0,'mobile navigation closes after route change');
 await page.getByRole('button',{name:'Add instrument',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 await page.keyboard.press('Escape');
 check(await page.getByRole('dialog').count() === 0,'Escape closes dialog');
 check(errors.length === 0,'no browser runtime or resource errors: '+errors.join('; '));
 console.log(passed+' browser checks passed. Screenshots: '+output);
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
